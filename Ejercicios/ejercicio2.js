/* Variables */
let num1 = 20;
let num2 = 6;

// Mostrar en consola
console.log(`Suma: ${num1 + num2}`);
console.log(`Resta: ${num1 - num2}`);
console.log(`Multiplicación: ${num1 * num2}`);
console.log(`División: ${(num1 / num2).toFixed(3)}`);
console.log(`Módulo: ${num1 % num2}`);
console.log(`Exponencial: ${num1 ** num2}`);